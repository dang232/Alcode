// Regenerates index.bundle.js from the engine source. Run with bun:
//   bun ./regen.js   (from this directory)
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { buildOmoNativeEntry } from './build-entry.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const header = '// Generated by regen.js — DO NOT EDIT BY HAND.\n// Native OmO platform plugin entry (single-file bundle, node:* externals only).\n';
const source = await buildOmoNativeEntry();
const nonNode = [...source.matchAll(/from ["']([^"']+)["']/g)]
  .map((match) => match[1])
  .filter((spec) => !spec.startsWith('node:'));
if (nonNode.length > 0) {
  throw new Error(`regen refused: non-node imports left: ${[...new Set(nonNode)].join(', ')}`);
}
await writeFile(path.join(here, 'index.bundle.js'), `${header}${source}`);
console.log(`index.bundle.js written (${source.length} bytes, node-only externals)`);
